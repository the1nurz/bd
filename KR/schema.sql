-- У pgAdmin 4 створіть порожню БД і відкрийте її Query Tool.
-- Виконуйте файли повністю: schema.sql, data.sql, oltp.sql, olap.sql.
-- schema.sql і data.sql призначені для першого запуску в порожній БД.
BEGIN;

CREATE TABLE clients (
    client_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company VARCHAR(150) NOT NULL,
    contact_name VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    phone VARCHAR(25),
    country VARCHAR(80) NOT NULL
);

CREATE TABLE freelancers (
    freelancer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    skills TEXT NOT NULL,
    daily_rate NUMERIC(10,2) NOT NULL CHECK (daily_rate > 0)
);

CREATE TABLE projects (
    project_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id INTEGER NOT NULL REFERENCES clients ON DELETE RESTRICT,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    country VARCHAR(80) NOT NULL,
    category VARCHAR(80) NOT NULL,
    budget NUMERIC(12,2) NOT NULL CHECK (budget > 0),
    created_at DATE NOT NULL DEFAULT CURRENT_DATE,
    deadline DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'open'
        CHECK (status IN ('open', 'in_progress', 'completed', 'cancelled')),
    CHECK (deadline >= created_at)
);

CREATE TABLE proposals (
    proposal_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id INTEGER NOT NULL REFERENCES projects ON DELETE RESTRICT,
    freelancer_id INTEGER NOT NULL REFERENCES freelancers ON DELETE RESTRICT,
    price NUMERIC(12,2) NOT NULL CHECK (price > 0),
    cover_letter TEXT NOT NULL,
    submitted_at DATE NOT NULL DEFAULT CURRENT_DATE,
    UNIQUE (project_id, freelancer_id)
);

-- Один контракт на одну пропозицію; сам контракт означає її прийняття.
CREATE TABLE contracts (
    contract_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposal_id INTEGER NOT NULL UNIQUE REFERENCES proposals ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'completed', 'cancelled')),
    started_at DATE NOT NULL,
    completed_at DATE,
    paid_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (paid_amount >= 0),
    CHECK (completed_at IS NULL OR completed_at >= started_at),
    CHECK ((status = 'completed' AND completed_at IS NOT NULL)
        OR (status <> 'completed' AND completed_at IS NULL))
);

COMMIT;
